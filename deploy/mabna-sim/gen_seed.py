#!/usr/bin/env python3
"""Generate generated/02-seed.sql: SYNTHETIC DEMONSTRATION DATA for the Mabna
simulator. Deterministic (fixed seed). No real data is read or embedded.

Usage:
  python3 deploy/mabna-sim/gen_seed.py [--map map.json] [--out DIR] [--rows N]

Built against the made-up example schema (SimCustomer / SimInvoice /
SimCheque). PENDING real capture: once the real schema is known, copy
example/seed-map.example.json to a gitignored file (e.g. generated/map.json),
set the real table/column names and status codes, and pass --map. Real names
therefore never enter tracked files (FR-02).

Edge cases deliberately produced:
  - Jalali dates as text 'yyyy/mm/dd' AND as numeric yyyymmdd (both columns).
  - Arabic ي/ك mixed with Persian ی/ک in names and notes.
  - Invoice statuses: normal, cancelled, returned. Cheques: uncleared,
    cleared, bounced. NULL dates / notes / phones. Some Persian digits in text.
"""
import argparse
import json
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))

DEFAULT_MAP = {
    "customer": {"table": "dbo.SimCustomer", "id": "CustId", "name": "CustName", "phone": "Phone"},
    "invoice": {"table": "dbo.SimInvoice", "id": "InvId", "customer": "CustId",
                "date_text": "InvDateText", "date_num": "InvDateNum",
                "status": "InvStatus", "amount": "Amount", "note": "Note",
                "status_codes": {"normal": 0, "cancelled": 1, "returned": 2}},
    "cheque": {"table": "dbo.SimCheque", "id": "ChqId", "customer": "CustId",
               "date_text": "DueDateText", "date_num": "DueDateNum",
               "status": "ChqState", "amount": "Amount", "note": "Note",
               "status_codes": {"uncleared": 0, "cleared": 1, "bounced": 2}},
}

# Mixed Arabic (ي U+064A, ك U+0643) and Persian (ی U+06CC, ک U+06A9) spellings.
NAMES = [
    "داروخانه دکتر کریمی", "داروخانه دكتر كريمي", "داروخانه شبانه‌روزی مهر",
    "داروخانه شبانه روزی مهر", "داروخانه نيك‌پور", "داروخانه نیکپور",
    "داروخانه یاس", "داروخانه ياس", "داروخانه کاظمی", "داروخانه كاظمي",
]
NOTES = [None, None, "تسويه نقدي", "تسویه نقدی", "فاکتور فروش كالا", "برگشت از فروش",
         "۱۴۰۳ پرداخت قسطی", "check ۱۲۳ synthetic"]


def jalali_days_in_month(m):
    return 31 if m <= 6 else 30


def rand_date(rng):
    y, m = rng.choice([1402, 1403, 1404]), rng.randint(1, 12)
    return y, m, rng.randint(1, jalali_days_in_month(m))


def lit(v):
    if v is None:
        return "NULL"
    if isinstance(v, str):
        return "N'" + v.replace("'", "''") + "'"
    return str(v)


def date_pair(rng, null_rate=0.05):
    if rng.random() < null_rate:
        return None, None
    y, m, d = rng.choice([rand_date(rng)])
    # text form sometimes without zero padding / with Persian digits
    txt = "%04d/%02d/%02d" % (y, m, d)
    if rng.random() < 0.1:
        txt = txt.translate(str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹"))
    return txt, y * 10000 + m * 100 + d


def emit(f, tname, cols, rows):
    for i in range(0, len(rows), 500):
        chunk = rows[i:i + 500]
        f.write("INSERT INTO %s (%s) VALUES\n" % (tname, ", ".join(cols)))
        f.write(",\n".join("    (" + ", ".join(lit(v) for v in r) + ")" for r in chunk))
        f.write(";\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--map")
    ap.add_argument("--out", default=os.path.join(HERE, "generated"))
    ap.add_argument("--rows", type=int, default=200)
    ap.add_argument("--db", default=None, help="database name for USE (default TotalSystem, or SimDb for the example)")
    a = ap.parse_args()
    m = DEFAULT_MAP
    if a.map:
        with open(a.map, encoding="utf-8") as fh:
            m = json.load(fh)
    rng = random.Random(20261114)
    os.makedirs(a.out, exist_ok=True)
    c, i, q = m["customer"], m["invoice"], m["cheque"]
    n_cust = max(10, a.rows // 10)

    with open(os.path.join(a.out, "02-seed.sql"), "w", encoding="utf-8") as f:
        f.write("-- ==================================================================\n"
                "-- SYNTHETIC DEMONSTRATION DATA - generated by gen_seed.py.\n"
                "-- Not real company data. Gitignored output; safe to delete/regenerate.\n"
                "-- ==================================================================\n")
        f.write("USE %s;\nGO\nSET NOCOUNT ON;\n" % (a.db or "TotalSystem"))
        # customers (explicit ids: IDENTITY_INSERT)
        rows = []
        for k in range(1, n_cust + 1):
            phone = None if rng.random() < 0.2 else "09%09d" % rng.randint(0, 10**9 - 1)
            rows.append((k, rng.choice(NAMES) + " " + str(k), phone))
        f.write("SET IDENTITY_INSERT %s ON;\n" % c["table"])
        emit(f, c["table"], [c["id"], c["name"], c["phone"]], rows)
        f.write("SET IDENTITY_INSERT %s OFF;\nGO\n" % c["table"])

        sc = i["status_codes"]
        weights = [("normal", 80), ("cancelled", 10), ("returned", 10)]
        rows = []
        for k in range(1, a.rows + 1):
            st = rng.choices([w[0] for w in weights], [w[1] for w in weights])[0]
            t, n = date_pair(rng)
            amt = rng.randint(1, 5000) * 10000
            if st == "returned":
                amt = -amt if rng.random() < 0.5 else amt  # both sign conventions
            rows.append((k, rng.randint(1, n_cust), t, n, sc[st], amt, rng.choice(NOTES)))
        f.write("SET IDENTITY_INSERT %s ON;\n" % i["table"])
        emit(f, i["table"], [i["id"], i["customer"], i["date_text"], i["date_num"],
                             i["status"], i["amount"], i["note"]], rows)
        f.write("SET IDENTITY_INSERT %s OFF;\nGO\n" % i["table"])

        sc = q["status_codes"]
        weights = [("uncleared", 40), ("cleared", 45), ("bounced", 15)]
        rows = []
        for k in range(1, a.rows // 2 + 1):
            st = rng.choices([w[0] for w in weights], [w[1] for w in weights])[0]
            t, n = date_pair(rng, 0.1)
            rows.append((k, rng.randint(1, n_cust), t, n, sc[st],
                         rng.randint(1, 3000) * 10000, rng.choice(NOTES)))
        f.write("SET IDENTITY_INSERT %s ON;\n" % q["table"])
        emit(f, q["table"], [q["id"], q["customer"], q["date_text"], q["date_num"],
                             q["status"], q["amount"], q["note"]], rows)
        f.write("SET IDENTITY_INSERT %s OFF;\nGO\n" % q["table"])
    print("wrote", os.path.join(a.out, "02-seed.sql"))


if __name__ == "__main__":
    main()
