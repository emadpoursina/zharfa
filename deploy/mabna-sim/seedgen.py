class C:
    """Column wrapper."""

    def __init__(self, d):
        self.d = d
        self.name = d["column_name"]
        self.t = (d.get("base_type") or d["type_name"]).lower()
        ml = int(d["max_length"])
        self.w = None if ml == -1 else (ml // 2 if self.t in ("nvarchar", "nchar") else ml)
        self.prec, self.scale = int(d["precision"]), int(d["scale"])
        self.null = gs.is_true(d["is_nullable"])
        self.ident = gs.is_true(d.get("is_identity", "0"))
        self.computed = gs.is_true(d.get("is_computed", "0"))
        self.text = self.t in ("char", "varchar", "nchar", "nvarchar")
        self.uni = self.t in ("nchar", "nvarchar")


def enc_varchar(s):
    """What a CP1256 varchar column can actually hold: Persian yeh folds to
    Arabic yeh, Persian digits to ASCII, anything else unencodable to '?'."""
    out = []
    for ch in s:
        if ch == "ی":
            ch = "ي"
        elif "۰" <= ch <= "۹":
            ch = chr(ord("0") + ord(ch) - 0x06F0)
        try:
            ch.encode("cp1256")
        except UnicodeEncodeError:
            ch = "?"
        out.append(ch)
    return "".join(out)


def jalali(rng, y=None):
    y = y or rng.choice([1402, 1403, 1403, 1404])
    mo = rng.randint(1, 12)
    return y, mo, rng.randint(1, 31 if mo <= 6 else 30)


def greg(rng):
    return datetime.datetime(2023, 3, 21) + datetime.timedelta(seconds=rng.randint(0, 3 * 365 * 86400))


def num_max(c):
    if c.t == "tinyint":
        return 255
    if c.t == "smallint":
        return 32767
    if c.t == "int":
        return 2147483647
    if c.t == "bigint":
        return 9 * 10 ** 15
    if c.t in ("numeric", "decimal"):
        return 10 ** (c.prec - c.scale) - 1
    return 10 ** 9


def lit(c, v):
    """SQL literal of python value v for column c."""
    if v is None:
        return "NULL"
    if c.text:
        s = str(v)
        if c.w is not None:
            s = s[:c.w]
        if c.uni:
            return "N'" + s.replace("'", "''") + "'"
        return "'" + enc_varchar(s).replace("'", "''") + "'"
    if c.t == "uniqueidentifier":
        return "'%s'" % v
    if c.t in ("datetime", "smalldatetime", "datetime2", "date"):
        return "'%s'" % v.strftime("%Y-%m-%dT%H:%M:%S")
    if c.t in ("binary", "varbinary", "image"):
        return "0x" + v.hex()
    if c.t in ("numeric", "decimal", "money", "smallmoney"):
        return "%.*f" % (c.scale if c.t in ("numeric", "decimal") else 2, v)
    if c.t in ("float", "real"):
        return repr(float(v))
    if isinstance(v, bool):
        return "1" if v else "0"
    return str(int(v))


# ---- Jalali calendar helpers (arithmetic 33-year-cycle algorithm) ------------
def jalali_to_gregorian(jy, jm, jd):
    jy += 1595
    days = -355668 + 365 * jy + (jy // 33) * 8 + ((jy % 33) + 3) // 4 + jd
    days += (jm - 1) * 31 if jm < 7 else ((jm - 7) * 30 + 186)
    gy = 400 * (days // 146097)
    days %= 146097
    if days > 36524:
        days -= 1
        gy += 100 * (days // 36524)
        days %= 36524
        if days >= 365:
            days += 1
    gy += 4 * (days // 1461)
    days %= 1461
    if days > 365:
        gy += (days - 1) // 365
        days = (days - 1) % 365
    gd = days + 1
    ml = [0, 31, 29 if (gy % 4 == 0 and gy % 100 != 0) or gy % 400 == 0 else 28,
          31, 30, 31, 30, 31, 31, 30, 31, 30, 31]
    gm = 0
    while gm < 13 and gd > ml[gm]:
        gd -= ml[gm]
        gm += 1
    return datetime.date(gy, gm, gd)


def gregorian_to_jalali(d):
    gy, gm, gd = d.year, d.month, d.day
    gdm = [0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334]
    gy2 = gy + 1 if gm > 2 else gy
    days = (355666 + 365 * gy + (gy2 + 3) // 4 - (gy2 + 99) // 100 + (gy2 + 399) // 400
            + gd + gdm[gm - 1])
    jy = -1595 + 33 * (days // 12053)
    days %= 12053
    jy += 4 * (days // 1461)
    days %= 1461
    if days > 365:
        jy += (days - 1) // 365
        days = (days - 1) % 365
    if days < 186:
        jm, jd = 1 + days // 31, 1 + days % 31
    else:
        jm, jd = 7 + (days - 186) // 30, 1 + (days - 186) % 30
    return jy, jm, jd


def jalali_add_days(jy, jm, jd, n):
    return gregorian_to_jalali(jalali_to_gregorian(jy, jm, jd) + datetime.timedelta(days=n))


def _conv(c, v):
    """lookups.txt text value -> python value for column wrapper c."""
    if v in ("", "NULL"):
        return None
    try:
        if c.text or c.t == "uniqueidentifier":
            return v
        if c.t == "bit":
            return 1 if v.strip().lower() in ("1", "true") else 0
        if c.t in ("tinyint", "smallint", "int", "bigint"):
            return int(v)
        if c.t in ("numeric", "decimal", "money", "smallmoney", "float", "real"):
            return float(v)
    except ValueError:
        pass
    return v


def run(capture, cfg, out_dir, db, selection=None, row_counts=None, lookups=None, scenario=None):
    """selection: optional selection.json written by gen_schema.py (tables to seed).
    lookups: lookups.txt dump; those tables are NOT generated (02a-lookups.sql
    loads them) but their real codes are used for FK values.
    scenario: path of a gitignored python file (may hold real names) with
    build_all(ctx) -> {table: [partial row dicts]} for tables that need
    hand-built, internally consistent data; see gen_seed.py."""
    keep = None
    if selection:
        with open(selection, encoding="utf-8") as fh:
            names = {n.lower() for n in json.load(fh)["tables"]}
        keep = {k for k in gs.load_model(capture).tables if k[1].lower() in names}
    m = gs.load_model(capture, selection=keep, row_counts=row_counts)
    rng = random.Random(20261114)
    colcfg = cfg.get("columns", {})
    rc_over = dict(cfg.get("row_counts", {}))
    scen = None
    if scenario:
        import importlib.util
        spec = importlib.util.spec_from_file_location("mabna_scenario", scenario)
        scen = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(scen)
        rc_over.update(getattr(scen, "ROW_COUNTS", {}))
    cols = {k: [C(d) for d in v] for k, v in m.tables.items()}
    cmap = {k: {c.name: c for c in v} for k, v in cols.items()}
    stub_cols = {k: [C(dict(c, column_name=n, is_nullable="0", is_identity="0", default_definition=""))
                     for n, (_, c) in v.items()] for k, v in m.stubs.items()}

    # FK graph among captured tables -> generation order
    fks_of = defaultdict(list)
    for f in m.fks:
        fks_of[f["from"]].append(f)
    order, seen = [], set()

    def visit(t, stack=()):
        if t in seen or t in stack:
            return
        for f in fks_of[t]:
            if not f["stub"] and f["to"] != t:
                visit(f["to"], stack + (t,))
        seen.add(t)
        order.append(t)

    for t in m.tables:
        visit(t)

    # Phase 6 example tables (made-up Sim* names only); seeded by seed_financial_table below.
    fin_tables = [t for t in order if t[1].lower() in FINANCIAL_EXAMPLE]
    fin_set = set(fin_tables)
    fin_keys = {}  # table -> list of seeded key values (instrument references across tables)

    def target(t):
        name = t[1]
        if name in rc_over:
            return int(rc_over[name])
        return max(5, min(2000, int(round(m.row_counts.get(t, 0) * 0.01))))

    rows = {t: [] for t in m.tables}
    stub_rows = {t: OrderedDict() for t in m.stubs}  # tuple -> dict
    stub_counter = defaultdict(int)
    index_cache = {}

    def lookup(parent, tocols, assigned):
        """Parent rows whose columns match the already assigned FK columns."""
        sub = tuple(tc for tc in tocols if tc in assigned)
        if not sub:
            return rows[parent]
        key = (parent, sub, len(rows[parent]))
        if key not in index_cache:
            ix = defaultdict(list)
            for r in rows[parent]:
                ix[tuple(r[c] for c in sub)].append(r)
            index_cache[key] = ix
        return index_cache[key].get(tuple(assigned[tc] for tc in sub), [])

    def stub_value(stub, c):
        stub_counter[(stub, c.name)] += 1
        n = stub_counter[(stub, c.name)]
        if c.text:
            return ("K%d" % n)[:c.w or 8]
        if c.t == "uniqueidentifier":
            return str(uuid.UUID(int=(0x5107 << 96) + n))
        return n

    seq_cache = {}

    def key_sets(t):
        ks = []
        if t in m.pk:
            ks.append(m.pk[t]["cols"])
        for e in m.indexes.get(t, []):
            if e["unique"]:
                ks.append([c for _, c, _ in e["keys"]])
        return ks

    def gen_table(t):
        cl = cols[t]
        byname = cmap[t]
        fks = sorted(fks_of[t], key=lambda f: (f["stub"], -len(f["cols"])))
        fkcols = {c for f in fks for c in f["cols"]}
        ks = key_sets(t)
        seqcols = set()
        keycols = set()
        for k in ks:
            keycols.update(k)
            free = [c for c in k if c not in fkcols and not byname[c].ident]
            if free:
                seqcols.add(free[-1])
        n_target = target(t)
        seen_keys = [set() for _ in ks]
        tname = t[1]
        out = rows[t]
        attempts = 0
        while len(out) < n_target and attempts < n_target * 6:
            attempts += 1
            n = len(out) + 1
            vals, ok = {}, True
            for f in fks:
                if f["to"] == t:
                    if all(byname[c].null for c in f["cols"]):
                        for c in f["cols"]:
                            vals.setdefault(c, None)
                    continue
                assigned = {tc: vals[fc] for fc, tc in zip(f["cols"], f["tocols"]) if fc in vals}
                if (not assigned and all(byname[c].null for c in f["cols"])
                        and not any(c in keycols for c in f["cols"]) and rng.random() < 0.06):
                    for c in f["cols"]:
                        vals[c] = None
                    continue
                if any(v is None for v in assigned.values()):
                    ok = False
                    break
                if f["stub"]:
                    reg = stub_rows[f["to"]]
                    match = [r for r in reg.values()
                             if all(r[tc] == v for tc, v in assigned.items())]
                    if not match or (len(reg) < 25 and rng.random() < 0.12):
                        new = {}
                        for sc in stub_cols[f["to"]]:
                            new[sc.name] = assigned[sc.name] if sc.name in assigned else stub_value(f["to"], sc)
                        tup = tuple(new[sc.name] for sc in stub_cols[f["to"]])
                        reg.setdefault(tup, new)
                        pr = reg[tup]
                    else:
                        pr = rng.choice(match)
                else:
                    cand = lookup(f["to"], f["tocols"], assigned)
                    if not cand:
                        ok = False
                        break
                    pr = rng.choice(cand)
                for fc, tc in zip(f["cols"], f["tocols"]):
                    vals[fc] = pr[tc]
            if not ok:
                continue
            for c in cl:
                if c.name in vals or c.computed:
                    continue
                v = gen_value(t, c, n, c.name in seqcols, c.name in keycols)
                if v is _FAIL:
                    ok = False
                    break
                vals[c.name] = v
            if not ok:
                continue
            tuples = [tuple(vals[c] for c in k) for k in ks]
            if any(tp in sk for tp, sk in zip(tuples, seen_keys)):
                continue
            for tp, sk in zip(tuples, seen_keys):
                sk.add(tp)
            out.append(vals)

    _FAIL = object()

    def default_of(c):
        d = (c.d.get("default_definition") or "").strip()
        while d.startswith("(") and d.endswith(")"):
            d = d[1:-1].strip()
        if re.fullmatch(r"-?\d+(\.\d+)?", d):
            return float(d) if "." in d else int(d)
        if d == "''":
            return ""
        if d.lower() == "newid()":
            return str(uuid.UUID(int=rng.getrandbits(128), version=4))
        return _FAIL

    def complete(t, part, n):
        """Fill every column the scenario row does not set: FK columns from a
        parent row (NULL when nullable), defaults, NULL, or a typed value."""
        vals = dict(part)
        byname = cmap[t]
        for f in fks_of[t]:
            missing = [c for c in f["cols"] if c not in vals]
            if not missing:
                continue
            if all(byname[c].null for c in missing):   # NULL part => FK not enforced
                for c in missing:
                    vals[c] = None
                continue
            if f["stub"]:
                raise ValueError("scenario row for %s needs a stub FK %s" % (t[1], f["cols"]))
            assigned = {tc: vals[fc] for fc, tc in zip(f["cols"], f["tocols"]) if fc in vals}
            cand = lookup(f["to"], f["tocols"], assigned)
            if not cand:
                raise ValueError("no parent row for %s.%s" % (t[1], f["cols"]))
            pr = rng.choice(cand)
            for fc, tc in zip(f["cols"], f["tocols"]):
                vals.setdefault(fc, pr[tc])
        for c in cols[t]:
            if c.name in vals or c.computed:
                continue
            d = default_of(c)
            if d is not _FAIL:
                vals[c.name] = d
            elif c.null:
                vals[c.name] = None
            else:
                v = typed_value(c, n)
                vals[c.name] = "0" if v is _FAIL else v
        return vals

    def text_for(c, n, uniq):
        nm = c.name
        w = c.w or 200
        if PHONE.search(nm):
            return ("09%09d" % rng.randint(0, 10 ** 9 - 1))[:w]
        if re.search(r"mail", nm, re.I):
            return ("sample%d@example.invalid" % n)[:w]
        if NAMEISH.search(nm) and w >= 6:
            base = rng.choice(FA_NAMES)
            s = "%s %d" % (base, n) if uniq or rng.random() < 0.6 else base
        elif DESCISH.search(nm) and w >= 8:
            s = rng.choice(FA_NOTES)
            if uniq:
                s += " %d" % n
        elif DIGITSISH.search(nm) and w >= 3:
            s = str(rng.randint(10 ** (min(w, 9) - 2), 10 ** (min(w, 9) - 1) - 1))
            if uniq:
                s = str(n)
        elif w <= 2:
            s = "ABCDEFGHJKLMNPQRSTUVWXYZ"[(n if uniq else rng.randint(0, 3)) % 24]
            if uniq and n > 24:
                return _FAIL
        else:
            s = "S%d" % n if uniq else "S%d" % rng.randint(1, 50)
        if uniq and len(s) > w:
            s = str(n)
            if len(s) > w:
                return _FAIL
        if c.uni and rng.random() < 0.3:
            s = s.translate(FA_DIGITS)
        return s[:w] if not uniq else s

    def date_value(c, n):
        y, mo, d = jalali(rng)
        if c.text:
            w = c.w or 10
            if w >= 10:
                return "%04d/%02d/%02d" % (y, mo, d)
            if w >= 8:
                return "%04d%02d%02d" % (y, mo, d)
            if w >= 6:
                return "%04d%02d" % (y, mo)
            return _FAIL
        if c.t in ("int", "bigint", "numeric", "decimal"):
            return y * 10000 + mo * 100 + d
        return None

    def gen_value(t, c, n, is_seq, is_key):
        spec = colcfg.get("%s.%s" % (t[1], c.name))
        if spec:
            if "cycle" in spec:
                return spec["cycle"][(n - 1) % len(spec["cycle"])]
            if "choices" in spec:
                vs, ws = zip(*spec["choices"])
                if c.null and rng.random() < spec.get("null_rate", 0):
                    return None
                return rng.choices(vs, ws)[0]
        nr = spec.get("null_rate") if spec else None
        if c.ident:
            return n
        if is_seq:
            return seq_value(c, n)
        if is_key:
            return const_value(c)
        if c.null and rng.random() < (0.08 if nr is None else nr):
            return None
        return typed_value(c, n)

    def seq_value(c, n):
        if c.text:
            return text_for(c, n, True)
        if c.t == "uniqueidentifier":
            return str(uuid.UUID(int=(0x5eed << 96) + n * 7919 + zlib.crc32(c.name.encode()) % 1000003))
        if c.t in ("datetime", "smalldatetime", "datetime2"):
            return datetime.datetime(2023, 3, 21) + datetime.timedelta(minutes=n)
        if c.t in ("binary", "varbinary"):
            return n.to_bytes(max(4, (c.w or 4) if c.w and c.w < 8 else 4), "big")[-(c.w or 4):]
        if c.t == "bit":
            return _FAIL if n > 2 else n - 1
        if n > num_max(c):
            return _FAIL
        return n

    def const_value(c):
        if c.text:
            return "A"
        if re.search(r"year", c.name, re.I) and c.t in ("smallint", "int", "bigint"):
            return 1403
        if c.t == "uniqueidentifier":
            return "00000000-0000-0000-0000-000000000001"
        if c.t in ("datetime", "smalldatetime", "datetime2"):
            return datetime.datetime(2024, 1, 1)
        if c.t == "bit":
            return 0
        return 1

    def typed_value(c, n):
        nm = c.name
        if re.search(r"date", nm, re.I) and (c.text or c.t in ("int", "bigint", "numeric", "decimal")):
            v = date_value(c, n)
            return (None if c.null else "0") if v is _FAIL else v
        if c.t in ("datetime", "smalldatetime", "datetime2", "date"):
            return greg(rng)
        if c.text:
            return text_for(c, n, False)
        if c.t == "uniqueidentifier":
            return str(uuid.UUID(int=rng.getrandbits(128), version=4))
        if c.t == "bit":
            return 1 if rng.random() < 0.2 else 0
        if c.t in ("binary", "varbinary", "image"):
            return None if c.null else bytes([rng.randint(0, 255)])
        if c.t == "tinyint":
            return rng.randint(0, 3)
        mx = num_max(c)
        if c.t in ("smallint", "int", "bigint") and re.search(r"year", nm, re.I):
            return rng.choice([1402, 1403, 1404]) if mx >= 1404 else 1
        if c.t in ("float", "real"):
            return round(rng.uniform(0, 1000), 2)
        if c.t in ("numeric", "decimal", "money", "smallmoney"):
            if c.scale:
                return round(rng.uniform(1, min(mx / 2, 500 if QTY.search(nm) else 5e6)), c.scale)
            if MONEY.search(nm):
                return min(rng.randint(1, 5000) * 10000, mx // 2 if mx > 1 else 1)
            return rng.randint(0, min(mx, 1000))
        # integers
        if MONEY.search(nm) and mx >= 10 ** 7:
            return rng.randint(1, 5000) * 10000
        return rng.randint(0, min(mx, 100))

    def seed_financial_table(t, out, fin_keys):
        """Build the demo rows of one made-up Sim* financial table (spec 008, T025). Partial dicts are
        completed by complete(); returns False when the shape is not recognised (caller then generates
        the table generically)."""
        kind = FINANCIAL_EXAMPLE[t[1].lower()]
        byname = {c.name.lower(): c for c in cols[t]}
        fks = [f for f in fks_of[t] if not f["stub"] and f["to"] != t]
        if not fks:
            return False
        vendor_fk = fks[0]
        parents = rows.get(vendor_fk["to"], [])
        if not parents:
            return False
        vkeys = [pr[vendor_fk["tocols"][0]] for pr in parents]
        vcol = vendor_fk["cols"][0]

        def find(*hints, required=True, exclude=()):
            for h in hints:
                for name, c in byname.items():
                    if h in name and not any(x in name for x in exclude):
                        return c
            if required:
                raise KeyError("%s: no column for %s" % (t[1], hints))
            return None

        def key_col():
            for c in cols[t]:
                if c.ident:
                    return c
            ks = key_sets(t)
            if ks:
                return byname[ks[0][0].lower()]
            return None

        def dval(c, jd):
            y, m, d = jd
            if c.t in ("tinyint", "smallint", "int", "bigint"):
                return y * 10000 + m * 100 + d
            if c.text:
                return "%04d/%02d/%02d" % (y, m, d)
            raise KeyError("%s: unsupported date column %s" % (t[1], c.name))

        def add(parts):
            for i, part in enumerate(parts, len(out) + 1):
                out.append(complete(t, part, i))

        try:
            kc = key_col()
            if kc is None:
                return False
            cancel = find("cancel", required=False)
            if kind == "document":
                date = find("docdate", "issuedate", "paydate", "date")
                amount = find("remain")
                number = find("number", "docno", required=False)
                base = len(out)
                parts = []
                for n, (jd, amt, ref, cancelled) in enumerate(FINANCIAL_DOCUMENTS, base + 1):
                    # vendors: the first three vendor rows take the payables; the rest stay payable-free
                    vk = vkeys[(n - 1) % min(3, len(vkeys))]
                    part = {kc.name: n, vcol: vk, date.name: dval(date, jd), amount.name: amt}
                    if cancel is not None:
                        part[cancel.name] = cancelled
                    if number is not None:
                        part[number.name] = ref
                    parts.append(part)
                add(parts)
                fin_keys[t] = [p[kc.name] for p in parts]
                return True
            if kind == "cheque":
                date = find("issuedate", "date")
                amount = find("amt", "amount")
                remain = find("remain")
                state = find("state")
                cleared = find("clear", required=False, exclude=("state",))
                instrument = find("tp", "type", required=False)
                number = find("chqnumber", "number", required=False)
                base = len(out)
                # (vendor slot, issue date, face, remaining, state, clear date, cancelled)
                spec = [
                    (0, (1405, 5, 1), 4000000, 4000000, "open", None, 0),                 # fully open
                    (0, (1405, 6, 15), 2500000, 2500000, "open", None, 0),                # fully open
                    (0, (1405, 6, 25), 1500000, 1500000, "cleared", (1405, 7, 10), 0),    # cleared after month end
                    (1, (1404, 9, 10), 3000000, 0, "cleared", (1405, 4, 20), 0),          # fully cleared
                    (1, (1405, 6, 1), 7000000, 2000000, "open", None, 0),                 # candidate partial-pay row
                    (2, (1405, 3, 3), 500000, 500000, "void", None, 1),                   # cancelled
                ]
                parts = []
                for n, (slot, jd, face, rem, st, clear, cancelled) in enumerate(spec, base + 1):
                    vk = vkeys[slot % len(vkeys)]
                    part = {kc.name: n, vcol: vk, date.name: dval(date, jd),
                            amount.name: face, remain.name: rem, state.name: st}
                    if cancel is not None:
                        part[cancel.name] = cancelled
                    if cleared is not None and clear is not None:
                        part[cleared.name] = dval(cleared, clear)
                    elif cleared is not None:
                        part[cleared.name] = None
                    if instrument is not None:
                        part[instrument.name] = "chq"
                    if number is not None:
                        part[number.name] = "CHQ-%04d" % n
                    parts.append(part)
                add(parts)
                fin_keys[t] = [p[kc.name] for p in parts]
                return True
            if kind == "payment":
                date = find("paydate", "date")
                amount = find("amt", "amount")
                instrument_col = find("tp", "type", required=False)
                number = find("paynumber", "number", required=False)
                link = find("chqid", "instrument", required=False)
                cheque_keys = next((v for k, v in fin_keys.items()
                                    if FINANCIAL_EXAMPLE.get(k[1].lower()) == "cheque"), None)
                base = len(out)
                # (vendor slot, date, amount, type, reference, cancelled); slot 1 = the vendor that also
                # has payables in 1405/07 (the purchase scenario dates its documents in the same month).
                spec = [
                    (0, (1405, 6, 20), 600000, "transfer", "PAY-1004", 0),
                    (0, (1405, 7, 12), 1750000, "cash", "PAY-1003", 0),
                    (0, (1405, 5, 5), 100000, "cash", "PAY-1007", 1),      # cancelled
                    (1, (1404, 9, 25), 3000000, "cheque", "PAY-1001", 0),   # settles the cleared cheque
                    (1, (1405, 7, 8), 5000000, "cheque", "PAY-1002", 0),    # partial pay of the 7M cheque
                    (1, (1405, 7, 21), 900000, "cash", "PAY-1006", 0),      # same month as PAYDOC-1006
                ]
                parts = []
                for n, (slot, jd, amt, tp, ref, cancelled) in enumerate(spec, base + 1):
                    vk = vkeys[slot % len(vkeys)]
                    part = {kc.name: n, vcol: vk, date.name: dval(date, jd), amount.name: amt}
                    if cancel is not None:
                        part[cancel.name] = cancelled
                    if instrument_col is not None:
                        part[instrument_col.name] = tp
                    if number is not None:
                        part[number.name] = ref
                    if link is not None and tp == "cheque" and cheque_keys and len(cheque_keys) >= 5:
                        # the cheque payments settle slot 1's cleared cheque (key index 3) and its
                        # partial-pay cheque (key index 4); cash and transfer payments carry no link.
                        part[link.name] = str(cheque_keys[4] if ref == "PAY-1002" else cheque_keys[3])
                    parts.append(part)
                add(parts)
                fin_keys[t] = [p[kc.name] for p in parts]
                return True
            # allocation: the split of one instrument across two vendors
            instrument = find("chqid", "instrument")
            amount = find("amt", "amount")
            cheque_keys = next((v for k, v in fin_keys.items()
                                if FINANCIAL_EXAMPLE.get(k[1].lower()) == "cheque"), None)
            if not cheque_keys:
                return False
            parts = []
            for n, slot in enumerate(range(2), len(out) + 1):
                part = {kc.name: n, vcol: vkeys[slot % len(vkeys)],
                        instrument.name: str(cheque_keys[4]), amount.name: 1000000}
                parts.append(part)
            add(parts)
            fin_keys[t] = [p[kc.name] for p in parts]
            return True
        except KeyError:
            return False

    # ---- lookup tables: real codes, loaded by 02a-lookups.sql, never generated
    lookup_tables = set()
    if lookups:
        lk, _ = gs.parse_lookups(lookups)
        byname = {k[1].lower(): k for k in m.tables}
        for name, (header, lrows) in lk.items():
            t = byname.get(name.lower())
            if t is None:
                continue
            lookup_tables.add(t)
            rows[t] = [{h: _conv(cmap[t][h], v) for h, v in zip(header, r) if h in cmap[t]}
                       for r in lrows]

    # ---- scenario tables (hand-built, consistent) and their FK descendants
    scen_tables, deferred = {}, set()
    if scen:
        want = {n.lower() for n in scen.TABLES}
        scen_tables = {t: t[1] for t in m.tables if t[1].lower() in want}
        kids = defaultdict(set)
        for f in m.fks:
            if not f["stub"] and f["to"] != f["from"]:
                kids[f["to"]].add(f["from"])
        todo = list(scen_tables)
        while todo:
            x = todo.pop()
            for k in kids[x]:
                if k not in deferred and k not in scen_tables:
                    deferred.add(k)
                    todo.append(k)

    for t in order:
        if t in lookup_tables or t in scen_tables or t in deferred or t in fin_set:
            continue
        gen_table(t)

    if scen:
        class Ctx:
            pass
        ctx = Ctx()
        ctx.rng = rng
        by_lower = {k[1].lower(): k for k in m.tables}
        ctx.rows = lambda name: rows[by_lower[name.lower()]]
        ctx.cols = lambda name: cols[by_lower[name.lower()]]
        ctx.j2g, ctx.g2j, ctx.jadd = jalali_to_gregorian, gregorian_to_jalali, jalali_add_days
        built = scen.build_all(ctx)
        for name, plist in built.items():
            t = by_lower[name.lower()]
            for i, part in enumerate(plist, 1):
                rows[t].append(complete(t, part, i))
        for t in order:
            if t in deferred and t not in fin_set:
                gen_table(t)

    # ---- example financials: made-up Sim* tables of the committed example capture (spec 008, T025).
    # A scenario that already seeded a table keeps its rows; an unrecognised shape falls back to the
    # generic filler, so a real capture is never seeded with the example values.
    for t in fin_tables:
        if rows[t] or t in lookup_tables or t in scen_tables:
            continue
        if not seed_financial_table(t, rows[t], fin_keys):
            gen_table(t)

    for t in m.stubs:  # at least three keys per stub
        reg = stub_rows[t]
        while len(reg) < 3:
            new = {sc.name: stub_value(t, sc) for sc in stub_cols[t]}
            reg.setdefault(tuple(new[sc.name] for sc in stub_cols[t]), new)

    os.makedirs(out_dir, exist_ok=True)
    total = 0
    with open(os.path.join(out_dir, "02b-seed.sql"), "w", encoding="utf-8") as f:
        f.write(HEADER)
        f.write("USE %s;\nGO\nSET NOCOUNT ON;\n" % gs.q(db))

        def emit(t, cl, data, ident):
            nonlocal total
            if not data:
                return
            names = ", ".join(gs.q(c.name) for c in cl)
            fq = "%s.%s" % (gs.q(t[0]), gs.q(t[1]))
            if ident:
                f.write("SET IDENTITY_INSERT %s ON;\n" % fq)
            for i in range(0, len(data), 500):
                f.write("INSERT INTO %s (%s) VALUES\n" % (fq, names))
                f.write(",\n".join("    (" + ", ".join(lit(c, r[c.name]) for c in cl) + ")"
                                   for r in data[i:i + 500]))
                f.write(";\n")
            if ident:
                f.write("SET IDENTITY_INSERT %s OFF;\n" % fq)
            f.write("GO\n")
            total += len(data)

        for t, cl in stub_cols.items():
            emit(t, cl, list(stub_rows[t].values()), False)
        for t in order:
            if t in lookup_tables:
                continue
            cl = [c for c in cols[t] if not c.computed]
            emit(t, cl, rows[t], any(c.ident for c in cl))
    print("wrote %s: %d tables + %d stubs, %d rows" % (
        os.path.join(out_dir, "02b-seed.sql"), len(order), len(m.stubs), total))
    for t in order:
        print("  %-28s target %5d  rows %5d" % (t[1], target(t), len(rows[t])))
    for t in m.stubs:
        print("  %-28s stub          rows %5d" % (t[1], len(stub_rows[t])))
