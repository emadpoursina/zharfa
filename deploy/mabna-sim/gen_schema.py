#!/usr/bin/env python3
"""Generate generated/00-database.sql and generated/01-schema.sql from the
output of scratch/mabna-schema-capture.sql (sqlcmd -s"|" -W result sets).

Usage:
  python3 deploy/mabna-sim/gen_schema.py <capture-output.txt> [--out DIR] [--db TotalSystem]

Input format (the "intermediate format"): sqlcmd text output where every
result set starts with a header row whose first field is `section`, optionally
followed by a dashes row, then pipe-separated data rows, then a blank line or
"(n rows affected)". Used sections:
  1b database       name|compatibility_level|collation_name|...
  4 columns         SchemaName|ObjectName|type_desc|ordinal|column_name|type_name|
                    base_type|max_length|precision|scale|is_nullable|is_identity|
                    is_computed|collation_name|identity_seed|identity_increment|
                    default_definition|computed_definition
  5 keys            SchemaName|ObjectName|constraint_name|type_desc|...|key_ordinal|column_name
  6 foreign_keys    fk_name|from_schema|from_table|from_column|to_schema|to_table|
                    to_column|column_ordinal|...
Only USER_TABLEs are created (views are skipped: a simulator needs tables).
Output goes to a gitignored dir because it contains real table/column names
(FR-02). Stdlib only. Example: deploy/mabna-sim/example/schema-capture.example.txt
"""
import argparse
import os
import sys
from collections import OrderedDict, defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))


def parse(path):
    """Return {section_key: [dict,...]} keyed by the section label."""
    sections = defaultdict(list)
    header = None
    with open(path, encoding="utf-8-sig") as fh:
        for raw in fh:
            line = raw.rstrip("\r\n")
            if not line.strip() or line.startswith("(") and "rows affected" in line:
                header = None
                continue
            parts = [p.strip() for p in line.split("|")]
            if parts[0] == "section":
                header = parts
                continue
            if header is None or set(line.replace("|", "").strip()) <= {"-"}:
                continue
            if len(parts) != len(header):
                continue  # wrapped/odd line; ignore
            row = dict(zip(header, parts))
            sections[row["section"]].append(row)
    return sections


def q(name):
    return "[" + name.replace("]", "]]") + "]"


def sql_type(c):
    t = c["type_name"].lower()
    ml, prec, sc = int(c["max_length"]), int(c["precision"]), int(c["scale"])
    if t in ("nvarchar", "nchar"):
        return "%s(%s)" % (t, "max" if ml == -1 else ml // 2)
    if t in ("varchar", "char", "varbinary", "binary"):
        return "%s(%s)" % (t, "max" if ml == -1 else ml)
    if t in ("decimal", "numeric"):
        return "%s(%d,%d)" % (t, prec, sc)
    if t in ("datetime2", "time", "datetimeoffset"):
        return "%s(%d)" % (t, sc)
    return t  # int, bigint, tinyint, smallint, bit, datetime, money, float, ...


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("capture")
    ap.add_argument("--out", default=os.path.join(HERE, "generated"))
    ap.add_argument("--db", default="TotalSystem")
    a = ap.parse_args()

    s = parse(a.capture)
    cols = [r for r in s.get("4 columns", []) if r.get("type_desc") == "USER_TABLE"]
    if not cols:
        sys.exit("no '4 columns' rows for USER_TABLEs found in " + a.capture)
    tables = OrderedDict()
    for r in cols:
        tables.setdefault((r["SchemaName"], r["ObjectName"]), []).append(r)
    for v in tables.values():
        v.sort(key=lambda r: int(r["ordinal"]))

    db_rows = s.get("1b database", [])
    collation = db_rows[0].get("collation_name") if db_rows else None
    if not collation or collation == "NULL":
        collation = None
        print("WARNING: no database collation in capture; using server default", file=sys.stderr)

    pks = defaultdict(list)
    for r in s.get("5 keys", []):
        if r.get("type_desc") == "PRIMARY_KEY_CONSTRAINT":
            pks[(r["SchemaName"], r["ObjectName"])].append(r)

    fks = OrderedDict()
    for r in s.get("6 foreign_keys", []):
        fks.setdefault((r["from_schema"], r["from_table"], r["fk_name"]), []).append(r)

    os.makedirs(a.out, exist_ok=True)
    hdr = ("-- GENERATED by deploy/mabna-sim/gen_schema.py from a schema capture.\n"
           "-- Contains real Mabna names when fed the real capture: gitignored (FR-02).\n"
           "-- No data. SYNTHETIC DEMONSTRATION DATA only is loaded by 02-seed.sql.\n")
    with open(os.path.join(a.out, "00-database.sql"), "w", encoding="utf-8") as f:
        f.write(hdr)
        f.write("IF DB_ID(N'%s') IS NULL\n    CREATE DATABASE %s%s;\nGO\n" % (
            a.db, q(a.db), (" COLLATE " + collation) if collation else ""))
        f.write("ALTER DATABASE %s SET COMPATIBILITY_LEVEL = 150;\nGO\n" % q(a.db))

    out = [hdr, "USE %s;\nGO\n" % q(a.db)]
    schemas = sorted({k[0] for k in tables if k[0] != "dbo"})
    for sc in schemas:
        out.append("IF SCHEMA_ID(N'%s') IS NULL EXEC(N'CREATE SCHEMA %s');\nGO\n" % (sc, q(sc)))
    skipped = 0
    for (sc, tb), cl in tables.items():
        lines = []
        for c in cl:
            if c.get("is_computed") == "1":
                lines.append("    %s AS %s" % (q(c["column_name"]), c["computed_definition"]))
                continue
            p = "    %s %s" % (q(c["column_name"]), sql_type(c))
            if c.get("collation_name") not in (None, "", "NULL"):
                p += " COLLATE " + c["collation_name"]
            if c.get("is_identity") == "1":
                p += " IDENTITY(%s,%s)" % (c.get("identity_seed") or 1, c.get("identity_increment") or 1)
            if c.get("default_definition") not in (None, "", "NULL"):
                p += " DEFAULT " + c["default_definition"]
            p += " NOT NULL" if c["is_nullable"] == "0" else " NULL"
            lines.append(p)
        k = pks.get((sc, tb))
        if k:
            k.sort(key=lambda r: int(r["key_ordinal"]))
            lines.append("    CONSTRAINT %s PRIMARY KEY (%s)" % (
                q(k[0]["constraint_name"]), ", ".join(q(r["column_name"]) for r in k)))
        out.append("CREATE TABLE %s.%s (\n%s\n);\nGO\n" % (q(sc), q(tb), ",\n".join(lines)))
    for (sc, tb, name), rs in fks.items():
        if (sc, tb) not in tables or (rs[0]["to_schema"], rs[0]["to_table"]) not in tables:
            skipped += 1
            continue
        rs.sort(key=lambda r: int(r["column_ordinal"]))
        act = ""
        for key, kw in (("delete_referential_action_desc", "DELETE"), ("update_referential_action_desc", "UPDATE")):
            v = rs[0].get(key, "NO_ACTION").replace("_", " ")
            if v != "NO ACTION":
                act += " ON %s %s" % (kw, v)
        out.append("ALTER TABLE %s.%s ADD CONSTRAINT %s FOREIGN KEY (%s)\n    REFERENCES %s.%s (%s)%s;\nGO\n" % (
            q(sc), q(tb), q(name), ", ".join(q(r["from_column"]) for r in rs),
            q(rs[0]["to_schema"]), q(rs[0]["to_table"]),
            ", ".join(q(r["to_column"]) for r in rs), act))
    with open(os.path.join(a.out, "01-schema.sql"), "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print("wrote %d tables, %d FKs (%d skipped: table not captured) to %s" % (
        len(tables), len(fks) - skipped, skipped, a.out))


if __name__ == "__main__":
    main()
