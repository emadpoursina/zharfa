-- 0001_init_canonical.sql — Canonical schema, constraints, indexes, and triggers for Zharfa Demo 1.
-- Stock PostgreSQL 18 forward-only migration. No extensions used.

-- 1. Product Category
CREATE TABLE product_category (
    category_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_fa text NOT NULL,
    is_active boolean NOT NULL DEFAULT true
);

-- 2. Product
CREATE TABLE product (
    product_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id bigint NOT NULL REFERENCES product_category(category_id),
    name_fa text NOT NULL,
    unit_fa text NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    has_batch boolean NOT NULL DEFAULT false
);

-- 3. Customer
CREATE TABLE customer (
    customer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_fa text NOT NULL,
    opening_balance numeric(18,2) NOT NULL DEFAULT 0.00,
    is_active boolean NOT NULL DEFAULT true
);

-- 4. Warehouse
CREATE TABLE warehouse (
    warehouse_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_fa text NOT NULL
);

-- 5. Sales Invoice (header)
CREATE TABLE sales_invoice (
    invoice_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES customer(customer_id),
    issued_at timestamptz NOT NULL,
    status text NOT NULL CHECK (status IN ('draft', 'posted', 'void')),
    note_fa text NULL
);

-- 6. Sales Invoice Item (line)
CREATE TABLE sales_invoice_item (
    item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id bigint NOT NULL REFERENCES sales_invoice(invoice_id),
    product_id bigint NOT NULL REFERENCES product(product_id),
    qty numeric(18,3) NOT NULL CHECK (qty <> 0),
    unit_price numeric(18,2) NOT NULL CHECK (unit_price >= 0),
    line_discount numeric(18,2) NOT NULL DEFAULT 0.00 CHECK (line_discount >= 0)
);

-- 7. Stock Movement
CREATE TABLE stock_movement (
    movement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES product(product_id),
    warehouse_id bigint NOT NULL REFERENCES warehouse(warehouse_id),
    moved_at timestamptz NOT NULL,
    qty_delta numeric(18,3) NOT NULL,
    reason text NOT NULL CHECK (reason IN ('sale', 'purchase-seed', 'adjustment')),
    batch_flag boolean NOT NULL DEFAULT false
);

-- 8. Receipt (receivables payment)
CREATE TABLE receipt (
    receipt_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES customer(customer_id),
    received_at timestamptz NOT NULL,
    amount numeric(18,2) NOT NULL CHECK (amount > 0)
);

-- 9. App User
CREATE TABLE app_user (
    user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username text NOT NULL UNIQUE,
    password_hash text NOT NULL,
    role text NOT NULL CHECK (role IN ('manager', 'admin')),
    is_active boolean NOT NULL DEFAULT true
);

-- 10. Audit Log (append-only)
CREATE TABLE audit_log (
    audit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at timestamptz NOT NULL DEFAULT now(),
    actor text NULL,
    action text NOT NULL,
    detail text NULL
);

-- 11. Reserved Table: source_record
-- FR-016: reserved for future Mabna integration; EMPTY in Demo 1 (no wiring, no reads)
CREATE TABLE source_record (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_system text NULL,
    payload text NULL,
    recorded_at timestamptz NULL
);

-- 12. Reserved Table: sync_job
-- FR-016: reserved for future Mabna integration; EMPTY in Demo 1 (no wiring, no reads)
CREATE TABLE sync_job (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_name text NULL,
    status text NULL,
    started_at timestamptz NULL,
    finished_at timestamptz NULL
);

-- 13. Reserved Table: sync_log
-- FR-016: reserved for future Mabna integration; EMPTY in Demo 1 (no wiring, no reads)
CREATE TABLE sync_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sync_job_id bigint NULL,
    level text NULL,
    message text NULL,
    logged_at timestamptz NULL
);

-- Foreign Key Indexes
CREATE INDEX idx_product_category_id ON product(category_id);
CREATE INDEX idx_sales_invoice_customer_id ON sales_invoice(customer_id);
CREATE INDEX idx_sales_invoice_item_invoice_id ON sales_invoice_item(invoice_id);
CREATE INDEX idx_sales_invoice_item_product_id ON sales_invoice_item(product_id);
CREATE INDEX idx_stock_movement_product_id ON stock_movement(product_id);
CREATE INDEX idx_stock_movement_warehouse_id ON stock_movement(warehouse_id);
CREATE INDEX idx_receipt_customer_id ON receipt(customer_id);

-- Operational and Query Filter Indexes
CREATE INDEX idx_sales_invoice_issued_at ON sales_invoice(issued_at);
CREATE INDEX idx_sales_invoice_status ON sales_invoice(status);
CREATE INDEX idx_stock_movement_moved_at ON stock_movement(moved_at);
CREATE INDEX idx_receipt_received_at ON receipt(received_at);

-- Audit Log Append-Only Guard (FR-017 / data-model.md)
CREATE FUNCTION fn_audit_log_append_only()
RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'audit_log is append-only; update and delete operations are prohibited';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_audit_log_append_only
BEFORE UPDATE OR DELETE ON audit_log
FOR EACH ROW
EXECUTE FUNCTION fn_audit_log_append_only();
