-- 0007_purchasing_reports.sql — Vendor and purchasing reports (Release 1, Phase 2, spec 004)
-- Forward-only, idempotent migration. Requires 0006_purchasing_kpis.sql.
-- Does not edit 0005/0006. Every Phase 1 figure is recomputed through mabna.fn_purchase_lines, which
-- carries the Phase 1 line-amount rule unchanged (research R1).

-- 1. Day key on purchase documents (research R2). Membership in a Jalali day range is then the same
-- as the Phase 1 month filter, because the key is built from the same stored jalali_* columns.
ALTER TABLE mabna.purchase_document
    ADD COLUMN IF NOT EXISTS jalali_key integer
    GENERATED ALWAYS AS (jalali_year * 10000 + jalali_month * 100 + jalali_day) STORED;

CREATE INDEX IF NOT EXISTS idx_purchase_document_jalali_key
    ON mabna.purchase_document (jalali_key)
    WHERE NOT cancelled;

CREATE INDEX IF NOT EXISTS idx_purchase_document_vendor_day
    ON mabna.purchase_document (vendor_id, jalali_key)
    WHERE NOT cancelled;

-- 2. Drug group master (research R7). One category level only; the key is the source key as text.
CREATE TABLE IF NOT EXISTS mabna.product_category (
    category_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key text NOT NULL UNIQUE,
    name_fa text NOT NULL,
    synced_at timestamptz NOT NULL
);

-- 3. Persian search key (research R6). One implementation for stored search columns and for the query term.
-- Maps ي and ى to ی, ك to ک, Persian and Arabic-Indic digits to Latin digits; removes whitespace, ZWNJ (U+200C),
-- tatweel (U+0640) and the separator '|'; lower-cases the result. NULL becomes ''. IMMUTABLE for generated columns.
CREATE OR REPLACE FUNCTION mabna.fn_search_key(p_text text)
RETURNS text
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
AS $$
    SELECT lower(
        translate(
            regexp_replace(coalesce(p_text, ''), '[[:space:]|‌ـ]', '', 'g'),
            'يىك۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩',
            'ییک' || '0123456789' || '0123456789'))
$$;

-- 4. Vendor code (optional, verified on-site as item 40) and search keys (research R6).
ALTER TABLE mabna.vendor ADD COLUMN IF NOT EXISTS code text NULL;

ALTER TABLE mabna.vendor
    ADD COLUMN IF NOT EXISTS search_key text
    GENERATED ALWAYS AS (mabna.fn_search_key(name_fa || '|' || coalesce(code, ''))) STORED;

ALTER TABLE mabna.product
    ADD COLUMN IF NOT EXISTS search_key text
    GENERATED ALWAYS AS (mabna.fn_search_key(name_fa)) STORED;

CREATE INDEX IF NOT EXISTS idx_product_drug_group_key
    ON mabna.product (drug_group_key);

CREATE INDEX IF NOT EXISTS idx_purchase_document_vendor_source_key
    ON mabna.purchase_document (vendor_source_key);

-- 5. Category search key.
ALTER TABLE mabna.product_category
    ADD COLUMN IF NOT EXISTS search_key text
    GENERATED ALWAYS AS (mabna.fn_search_key(name_fa)) STORED;

-- 6. mabna.fn_purchase_lines(): the range base (research R1, data-model.md §2). One row per line of every
-- non-cancelled purchase document whose jalali_key lies in [p_from_key, p_to_key] (yyyymmdd integers).
-- The document-discount allocation is moved verbatim from 0006's fn_purchase_line_amounts: integer units of
-- 0.0001, round half away from zero, the remainder to the largest line (ties: lowest line key, COLLATE "C"),
-- partitioned by document over all lines of the document. The allocation does not depend on the range,
-- because a document is either wholly inside the range or outside it.
-- Line amount = gross_amount - discount_amount (the Phase 1 line amount).
-- sign = +1 for invoices, -1 for returns. STABLE, read-only, SECURITY INVOKER.
CREATE OR REPLACE FUNCTION mabna.fn_purchase_lines(
    p_from_key int,
    p_to_key int,
    p_basis text DEFAULT 'line')
RETURNS TABLE (
    doc_type text,
    document_id bigint,
    line_id bigint,
    jalali_year smallint,
    jalali_month smallint,
    jalali_key integer,
    vendor_id bigint,
    vendor_source_key text,
    product_id bigint,
    product_source_key text,
    category_key text,
    category_id bigint,
    quantity numeric,
    gross_amount numeric,
    discount_amount numeric,
    line_amount numeric,
    vat_amount numeric,
    sign integer)
LANGUAGE sql
STABLE
SECURITY INVOKER
AS $$
    WITH lines_all AS (
        SELECT d.document_id,
               d.doc_type,
               d.jalali_year,
               d.jalali_month,
               d.jalali_key,
               d.vendor_id,
               d.vendor_source_key,
               l.line_id,
               l.source_key AS line_key,
               l.product_id,
               l.product_source_key,
               l.quantity,
               l.gross_amount,
               l.vat_amount,
               ((l.gross_amount - l.line_discount) * 10000)::numeric AS amount_units,
               (d.doc_discount * 10000)::numeric AS discount_units
        FROM mabna.purchase_document d
        JOIN mabna.purchase_line l ON l.document_id = d.document_id
        WHERE NOT d.cancelled
          AND d.jalali_key BETWEEN p_from_key AND p_to_key
    ),
    ranked AS (
        SELECT la.*,
               sum(la.amount_units) OVER (PARTITION BY la.document_id) AS doc_units,
               row_number() OVER (PARTITION BY la.document_id
                                  ORDER BY la.amount_units DESC, la.line_key COLLATE "C") AS line_rank
        FROM lines_all la
    ),
    raw_shares AS (
        SELECT r.*,
               CASE WHEN p_basis = 'lineAndDocument' AND r.discount_units <> 0 AND r.doc_units <> 0
                    THEN sign(r.discount_units * r.amount_units) * sign(r.doc_units)
                         * div(2 * abs(r.discount_units * r.amount_units) + abs(r.doc_units),
                               2 * abs(r.doc_units))
                    ELSE 0 END AS raw_units
        FROM ranked r
    ),
    shares AS (
        SELECT w.*,
               CASE WHEN p_basis = 'lineAndDocument'
                    THEN w.raw_units
                         + CASE WHEN w.line_rank = 1
                                THEN w.discount_units - sum(w.raw_units) OVER (PARTITION BY w.document_id)
                                ELSE 0 END
                    ELSE 0 END AS share_units
        FROM raw_shares w
    ),
    amounts AS (
        SELECT s.*,
               ((s.amount_units - s.share_units) / 10000)::numeric(24,4) AS line_amt
        FROM shares s
    )
    SELECT a.doc_type,
           a.document_id,
           a.line_id,
           a.jalali_year,
           a.jalali_month,
           a.jalali_key,
           a.vendor_id,
           a.vendor_source_key,
           a.product_id,
           a.product_source_key,
           p.drug_group_key,
           pc.category_id,
           a.quantity,
           a.gross_amount,
           (a.gross_amount - a.line_amt)::numeric(24,4),
           a.line_amt,
           a.vat_amount,
           CASE WHEN a.doc_type = 'return' THEN -1 ELSE 1 END
    FROM amounts a
    LEFT JOIN mabna.product p ON p.product_id = a.product_id
    LEFT JOIN mabna.product_category pc ON pc.source_key = p.drug_group_key
$$;

-- 7. mabna.fn_purchase_line_amounts(): the Phase 1 month function, now a thin wrapper over fn_purchase_lines
-- (same signature and output columns). Month bounds are day keys [yyyymm01, yyyymm31]; jalali_day <= 31 by CHECK.
CREATE OR REPLACE FUNCTION mabna.fn_purchase_line_amounts(
    p_year smallint,
    p_month smallint,
    p_vendor_key text DEFAULT NULL,
    p_product_key text DEFAULT NULL,
    p_basis text DEFAULT 'line')
RETURNS TABLE (
    doc_type text,
    document_id bigint,
    line_id bigint,
    product_source_key text,
    line_amount numeric,
    vat_amount numeric)
LANGUAGE sql
STABLE
SECURITY INVOKER
AS $$
    SELECT f.doc_type, f.document_id, f.line_id, f.product_source_key, f.line_amount, f.vat_amount
    FROM mabna.fn_purchase_lines(
             p_year::int * 10000 + p_month::int * 100 + 1,
             p_year::int * 10000 + p_month::int * 100 + 31,
             p_basis) f
    WHERE (p_vendor_key IS NULL OR f.vendor_source_key = p_vendor_key)
      AND (p_product_key IS NULL OR f.product_source_key = p_product_key)
$$;

-- 8. mabna.fn_sync_fingerprint(): extended with vendor.code, product.drug_group_key and the drug group master.
-- Generated columns (search_key, jalali_key) are excluded.
CREATE OR REPLACE FUNCTION mabna.fn_sync_fingerprint()
RETURNS TABLE (table_name text, row_count bigint, content_hash text)
LANGUAGE sql
STABLE
SECURITY INVOKER
AS $$
    SELECT 'vendor'::text,
           count(*),
           md5(coalesce(string_agg(concat_ws('|', source_key, name_fa, is_active_source::text, code), E'\n' ORDER BY source_key), ''))
    FROM mabna.vendor
    UNION ALL
    SELECT 'product'::text,
           count(*),
           md5(coalesce(string_agg(concat_ws('|', source_key, name_fa, drug_group_key), E'\n' ORDER BY source_key), ''))
    FROM mabna.product
    UNION ALL
    SELECT 'product_category'::text,
           count(*),
           md5(coalesce(string_agg(concat_ws('|', source_key, name_fa), E'\n' ORDER BY source_key), ''))
    FROM mabna.product_category
    UNION ALL
    SELECT 'purchase_invoice'::text,
           count(*),
           md5(coalesce(string_agg(concat_ws('|', source_key, doc_number, vendor_source_key, doc_date::text,
                                             cancelled::text, doc_discount::text),
                                   E'\n' ORDER BY source_key), ''))
    FROM mabna.purchase_document
    WHERE doc_type = 'invoice'
    UNION ALL
    SELECT 'purchase_return'::text,
           count(*),
           md5(coalesce(string_agg(concat_ws('|', source_key, doc_number, vendor_source_key, doc_date::text,
                                             cancelled::text, doc_discount::text),
                                   E'\n' ORDER BY source_key), ''))
    FROM mabna.purchase_document
    WHERE doc_type = 'return'
    UNION ALL
    SELECT 'purchase_line'::text,
           count(*),
           md5(coalesce(string_agg(concat_ws('|', d.doc_type, d.source_key, l.source_key, l.product_source_key,
                                             l.quantity::text, l.gross_amount::text, l.line_discount::text,
                                             l.vat_amount::text),
                                   E'\n' ORDER BY d.doc_type, d.source_key, l.source_key), ''))
    FROM mabna.purchase_line l
    JOIN mabna.purchase_document d ON d.document_id = l.document_id
$$;
