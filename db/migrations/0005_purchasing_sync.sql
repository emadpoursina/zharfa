-- 0005_purchasing_sync.sql — Schema and bookkeeping for Mabna purchasing sync (Release 1, Phase 1)
-- Forward-only, idempotent migration.

-- 1. Dedicated mabna schema for synced operational data
CREATE SCHEMA IF NOT EXISTS mabna;

-- 2. mabna.vendor
CREATE TABLE IF NOT EXISTS mabna.vendor (
    vendor_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key text NOT NULL UNIQUE,
    name_fa text NOT NULL,
    is_active_source boolean NULL,
    synced_at timestamptz NOT NULL
);

-- 3. mabna.product
CREATE TABLE IF NOT EXISTS mabna.product (
    product_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key text NOT NULL UNIQUE,
    name_fa text NOT NULL,
    drug_group_key text NULL,
    synced_at timestamptz NOT NULL
);

-- 4. mabna.purchase_document
CREATE TABLE IF NOT EXISTS mabna.purchase_document (
    document_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key text NOT NULL,
    doc_type text NOT NULL CHECK (doc_type IN ('invoice', 'return')),
    doc_number text NULL,
    vendor_source_key text NULL,
    vendor_id bigint NULL REFERENCES mabna.vendor(vendor_id),
    doc_date date NOT NULL,
    jalali_year smallint NOT NULL,
    jalali_month smallint NOT NULL CHECK (jalali_month BETWEEN 1 AND 12),
    jalali_day smallint NOT NULL CHECK (jalali_day BETWEEN 1 AND 31),
    cancelled boolean NOT NULL DEFAULT false,
    doc_discount numeric(24,4) NOT NULL DEFAULT 0 CHECK (doc_discount >= 0),
    synced_at timestamptz NOT NULL,
    CONSTRAINT uq_purchase_document_type_key UNIQUE (doc_type, source_key)
);

CREATE INDEX IF NOT EXISTS idx_purchase_document_jalali_period
    ON mabna.purchase_document (jalali_year, jalali_month)
    WHERE NOT cancelled;

CREATE INDEX IF NOT EXISTS idx_purchase_document_vendor_id
    ON mabna.purchase_document (vendor_id);

CREATE INDEX IF NOT EXISTS idx_purchase_document_doc_date
    ON mabna.purchase_document (doc_date);

-- 5. mabna.purchase_line
CREATE TABLE IF NOT EXISTS mabna.purchase_line (
    line_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id bigint NOT NULL REFERENCES mabna.purchase_document(document_id) ON DELETE CASCADE,
    source_key text NOT NULL,
    product_source_key text NULL,
    product_id bigint NULL REFERENCES mabna.product(product_id),
    quantity numeric(24,4) NULL,
    gross_amount numeric(24,4) NOT NULL,
    line_discount numeric(24,4) NOT NULL DEFAULT 0 CHECK (line_discount >= 0),
    vat_amount numeric(24,4) NULL,
    CONSTRAINT uq_purchase_line_doc_key UNIQUE (document_id, source_key)
);

CREATE INDEX IF NOT EXISTS idx_purchase_line_product_id
    ON mabna.purchase_line (product_id);

-- 6. Extensions to sync_job
ALTER TABLE sync_job ADD COLUMN IF NOT EXISTS trigger text;
ALTER TABLE sync_job ADD COLUMN IF NOT EXISTS mode text;
ALTER TABLE sync_job ADD COLUMN IF NOT EXISTS requested_by text;
ALTER TABLE sync_job ADD COLUMN IF NOT EXISTS duration_ms bigint;
ALTER TABLE sync_job ADD COLUMN IF NOT EXISTS error_message text;
ALTER TABLE sync_job ADD COLUMN IF NOT EXISTS skip_reason text;

-- trigger and mode are NOT NULL per data-model.md §2. sync_job is empty in Demo 1,
-- so SET NOT NULL is safe; it is a no-op on re-run.
ALTER TABLE sync_job ALTER COLUMN trigger SET NOT NULL;
ALTER TABLE sync_job ALTER COLUMN mode SET NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_sync_job_trigger') THEN
        ALTER TABLE sync_job ADD CONSTRAINT chk_sync_job_trigger CHECK (trigger IN ('manual', 'scheduled', 'startup-recovery'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_sync_job_mode') THEN
        ALTER TABLE sync_job ADD CONSTRAINT chk_sync_job_mode CHECK (mode IN ('incremental', 'full'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_sync_job_status') THEN
        ALTER TABLE sync_job ADD CONSTRAINT chk_sync_job_status CHECK (status IN ('running', 'succeeded', 'failed', 'skipped'));
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS uq_sync_job_running
    ON sync_job ((true))
    WHERE status = 'running';

-- 7. Extensions to sync_log
ALTER TABLE sync_log ADD COLUMN IF NOT EXISTS table_logical text;
ALTER TABLE sync_log ADD COLUMN IF NOT EXISTS rows_read integer;
ALTER TABLE sync_log ADD COLUMN IF NOT EXISTS rows_inserted integer;
ALTER TABLE sync_log ADD COLUMN IF NOT EXISTS rows_updated integer;
ALTER TABLE sync_log ADD COLUMN IF NOT EXISTS rows_deleted integer;
ALTER TABLE sync_log ADD COLUMN IF NOT EXISTS rows_rejected integer;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_sync_log_level') THEN
        ALTER TABLE sync_log ADD CONSTRAINT chk_sync_log_level CHECK (level IN ('info', 'warning', 'error'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_sync_log_job_id') THEN
        ALTER TABLE sync_log ADD CONSTRAINT fk_sync_log_job_id FOREIGN KEY (sync_job_id) REFERENCES sync_job(id) ON DELETE CASCADE;
    END IF;
END $$;

-- 8. Extensions to source_record
ALTER TABLE source_record ADD COLUMN IF NOT EXISTS table_logical text;
ALTER TABLE source_record ADD COLUMN IF NOT EXISTS strategy text;
ALTER TABLE source_record ADD COLUMN IF NOT EXISTS watermark text;
ALTER TABLE source_record ADD COLUMN IF NOT EXISTS last_full_load_at timestamptz;

-- table_logical and strategy are NOT NULL per data-model.md §2 (source_record is empty in Demo 1).
ALTER TABLE source_record ALTER COLUMN table_logical SET NOT NULL;
ALTER TABLE source_record ALTER COLUMN strategy SET NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_source_record_strategy') THEN
        ALTER TABLE source_record ADD CONSTRAINT chk_source_record_strategy CHECK (strategy IN ('rowversion', 'modifiedAt', 'idWatermark', 'full'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uq_source_record_system_table') THEN
        ALTER TABLE source_record ADD CONSTRAINT uq_source_record_system_table UNIQUE (source_system, table_logical);
    END IF;
END $$;

-- 9. install_setting
CREATE TABLE IF NOT EXISTS install_setting (
    key text PRIMARY KEY,
    value text NOT NULL,
    set_at timestamptz NOT NULL
);

-- 10. reconciliation_run
CREATE TABLE IF NOT EXISTS reconciliation_run (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_at timestamptz NOT NULL,
    jalali_month text NOT NULL,
    filter_kind text NOT NULL CHECK (filter_kind IN ('none', 'vendor', 'product')),
    filter_value text NULL,
    metric text NOT NULL CHECK (metric IN ('net', 'gross', 'returns', 'vat')),
    system_total numeric(24,4) NULL,
    source_total numeric(24,4) NULL,
    difference numeric(24,4) NULL,
    outcome text NOT NULL CHECK (outcome IN ('pass', 'mismatch', 'unavailable', 'error')),
    discount_basis text NOT NULL,
    data_mode text NOT NULL
);
