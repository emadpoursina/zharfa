-- 0011_vendor_financials.sql — Vendor financials sync tables and formula functions (Release 1, Phase 6)
-- Forward-only, idempotent migration. Requires 0010_ai_reports_export.sql.
-- Spec: specs/008-vendor-financials/data-model.md §1. Does not edit 0001–0010 and does not change any
-- purchasing table or fn_purchase_totals: purchases stay cited from the Phase 1 net (docs/metrics/purchasing.md).

-- 1. mabna.payable_document — open accounting payables / credit notes (entity payableDocument).
--    remaining_amount is SIGNED: negative = credit note in the vendor's favour (research R3).
CREATE TABLE IF NOT EXISTS mabna.payable_document (
    payable_document_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key text NOT NULL UNIQUE,
    vendor_source_key text NULL,
    vendor_id bigint NULL REFERENCES mabna.vendor(vendor_id),
    doc_date date NOT NULL,
    jalali_year smallint NOT NULL,
    jalali_month smallint NOT NULL CHECK (jalali_month BETWEEN 1 AND 12),
    jalali_day smallint NOT NULL CHECK (jalali_day BETWEEN 1 AND 31),
    doc_number text NULL,
    remaining_amount numeric(24,4) NOT NULL,
    cancelled boolean NOT NULL DEFAULT false,
    synced_at timestamptz NOT NULL
);

ALTER TABLE mabna.payable_document
    ADD COLUMN IF NOT EXISTS jalali_key integer
    GENERATED ALWAYS AS (jalali_year * 10000 + jalali_month * 100 + jalali_day) STORED;

CREATE INDEX IF NOT EXISTS idx_payable_document_vendor_date
    ON mabna.payable_document (vendor_id, doc_date)
    WHERE NOT cancelled;

CREATE INDEX IF NOT EXISTS idx_payable_document_vendor_source_key
    ON mabna.payable_document (vendor_source_key);

-- 2. mabna.payable_cheque — payable instruments (entity payableCheque). Amounts non-negative;
--    an open cheque's unpaid remainder lives here (research R4, FR-033: history holds the paid portion).
CREATE TABLE IF NOT EXISTS mabna.payable_cheque (
    payable_cheque_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key text NOT NULL UNIQUE,
    vendor_source_key text NULL,
    vendor_id bigint NULL REFERENCES mabna.vendor(vendor_id),
    issue_date date NOT NULL,
    jalali_year smallint NOT NULL,
    jalali_month smallint NOT NULL CHECK (jalali_month BETWEEN 1 AND 12),
    jalali_day smallint NOT NULL CHECK (jalali_day BETWEEN 1 AND 31),
    reference text NULL,
    instrument_type text NOT NULL,
    state text NOT NULL,
    amount numeric(24,4) NOT NULL CHECK (amount >= 0),
    remaining_amount numeric(24,4) NOT NULL CHECK (remaining_amount >= 0),
    cleared_at date NULL,
    cancelled boolean NOT NULL DEFAULT false,
    synced_at timestamptz NOT NULL
);

ALTER TABLE mabna.payable_cheque
    ADD COLUMN IF NOT EXISTS jalali_key integer
    GENERATED ALWAYS AS (jalali_year * 10000 + jalali_month * 100 + jalali_day) STORED;

CREATE INDEX IF NOT EXISTS idx_payable_cheque_vendor_issue_date
    ON mabna.payable_cheque (vendor_id, issue_date)
    WHERE NOT cancelled;

CREATE INDEX IF NOT EXISTS idx_payable_cheque_vendor_source_key
    ON mabna.payable_cheque (vendor_source_key);

-- 3. mabna.vendor_payment — completed payments (entity vendorPayment). amount is the PAID PORTION only.
CREATE TABLE IF NOT EXISTS mabna.vendor_payment (
    vendor_payment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key text NOT NULL UNIQUE,
    vendor_source_key text NULL,
    vendor_id bigint NULL REFERENCES mabna.vendor(vendor_id),
    paid_at date NOT NULL,
    jalali_year smallint NOT NULL,
    jalali_month smallint NOT NULL CHECK (jalali_month BETWEEN 1 AND 12),
    jalali_day smallint NOT NULL CHECK (jalali_day BETWEEN 1 AND 31),
    reference text NULL,
    instrument_type text NOT NULL,
    amount numeric(24,4) NOT NULL CHECK (amount >= 0),
    instrument_source_key text NULL,
    cancelled boolean NOT NULL DEFAULT false,
    synced_at timestamptz NOT NULL
);

ALTER TABLE mabna.vendor_payment
    ADD COLUMN IF NOT EXISTS jalali_key integer
    GENERATED ALWAYS AS (jalali_year * 10000 + jalali_month * 100 + jalali_day) STORED;

CREATE INDEX IF NOT EXISTS idx_vendor_payment_vendor_paid_at
    ON mabna.vendor_payment (vendor_id, paid_at)
    WHERE NOT cancelled;

CREATE INDEX IF NOT EXISTS idx_vendor_payment_vendor_source_key
    ON mabna.vendor_payment (vendor_source_key);

-- 4. mabna.payment_allocation — optional split of one instrument across vendors (entity paymentAllocation).
--    Created/synced only when the entity is mapped (data-model.md §1.4).
CREATE TABLE IF NOT EXISTS mabna.payment_allocation (
    allocation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key text NOT NULL UNIQUE,
    instrument_source_key text NOT NULL,
    vendor_source_key text NOT NULL,
    amount numeric(24,4) NOT NULL,
    synced_at timestamptz NOT NULL
);

-- 5. Formula functions (single definition; VendorFinancialTotals recomputes the same mix for reconciliation).
--    Signed candidate mix (research R1): non-cancelled payable documents with doc_date <= as_of, plus
--    non-cancelled cheques issued on or before as_of that were not fully cleared on or before as_of.
CREATE OR REPLACE FUNCTION mabna.fn_vendor_balance(
    p_as_of date,
    p_vendor_source_key text DEFAULT NULL)
RETURNS numeric
LANGUAGE sql
STABLE
SECURITY INVOKER
AS $$
    SELECT COALESCE((
        SELECT SUM(d.remaining_amount)
        FROM mabna.payable_document d
        WHERE NOT d.cancelled
          AND d.doc_date <= p_as_of
          AND (p_vendor_source_key IS NULL OR d.vendor_source_key = p_vendor_source_key)
    ), 0)::numeric
    + COALESCE((
        SELECT SUM(c.remaining_amount)
        FROM mabna.payable_cheque c
        WHERE NOT c.cancelled
          AND c.issue_date <= p_as_of
          AND (c.cleared_at IS NULL OR c.cleared_at > p_as_of)
          AND (p_vendor_source_key IS NULL OR c.vendor_source_key = p_vendor_source_key)
    ), 0)::numeric
$$;

-- Outstanding payments: non-negative unpaid remainder of instruments still open as of the period end.
-- History rows (vendor_payment) are never included (FR-033).
CREATE OR REPLACE FUNCTION mabna.fn_outstanding_payments(
    p_as_of date,
    p_vendor_source_key text DEFAULT NULL)
RETURNS numeric
LANGUAGE sql
STABLE
SECURITY INVOKER
AS $$
    SELECT COALESCE((
        SELECT SUM(c.remaining_amount)
        FROM mabna.payable_cheque c
        WHERE NOT c.cancelled
          AND c.issue_date <= p_as_of
          AND (c.cleared_at IS NULL OR c.cleared_at > p_as_of)
          AND (p_vendor_source_key IS NULL OR c.vendor_source_key = p_vendor_source_key)
    ), 0)::numeric
$$;

-- Payments: the paid portion whose payment or clear date falls inside the period. Never the unpaid remainder.
CREATE OR REPLACE FUNCTION mabna.fn_vendor_payments(
    p_from_date date,
    p_to_date date,
    p_vendor_source_key text DEFAULT NULL)
RETURNS numeric
LANGUAGE sql
STABLE
SECURITY INVOKER
AS $$
    SELECT COALESCE((
        SELECT SUM(p.amount)
        FROM mabna.vendor_payment p
        WHERE NOT p.cancelled
          AND p.paid_at >= p_from_date
          AND p.paid_at <= p_to_date
          AND (p_vendor_source_key IS NULL OR p.vendor_source_key = p_vendor_source_key)
    ), 0)::numeric
$$;

-- 6. saved_report: widen kind and required_permission for the four financial kinds (research R10).
--    required_permission is assigned by the server from the kind, never by the client.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_saved_report_kind') THEN
        ALTER TABLE saved_report DROP CONSTRAINT chk_saved_report_kind;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_saved_report_kind') THEN
        ALTER TABLE saved_report ADD CONSTRAINT chk_saved_report_kind CHECK (
            kind IN (
                'by-vendor',
                'by-product',
                'by-category',
                'trend',
                'top-products',
                'returns',
                'transactions',
                'vendors',
                'vendors-compare',
                'drill-down',
                'vendor-profile',
                'generated',
                'vendor-financials',
                'vendor-financials-history',
                'vendor-financials-outstanding',
                'vendor-financials-purchases-vs-payments'
            )
        );
    END IF;

    IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_saved_report_permission') THEN
        ALTER TABLE saved_report DROP CONSTRAINT chk_saved_report_permission;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_saved_report_permission') THEN
        ALTER TABLE saved_report ADD CONSTRAINT chk_saved_report_permission CHECK (
            required_permission IN ('purchasing.reports', 'ai.query', 'vendor.financials')
        );
    END IF;
END $$;

-- 7. reconciliation_run: the vendor-balance metric (research R11). discount_basis stays a text column and
--    stores '-' for this metric (the balance mix does not use the purchasing discount basis).
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_reconciliation_run_metric') THEN
        ALTER TABLE reconciliation_run DROP CONSTRAINT chk_reconciliation_run_metric;
    END IF;
    -- The Phase 1 column check was created inline and carries the auto-generated name.
    IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'reconciliation_run_metric_check') THEN
        ALTER TABLE reconciliation_run DROP CONSTRAINT reconciliation_run_metric_check;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_reconciliation_run_metric') THEN
        ALTER TABLE reconciliation_run ADD CONSTRAINT chk_reconciliation_run_metric CHECK (
            metric IN ('net', 'gross', 'returns', 'vat', 'vendor_balance')
        );
    END IF;
END $$;

